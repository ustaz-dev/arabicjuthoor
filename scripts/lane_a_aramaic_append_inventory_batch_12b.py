def append_scan() -> None:
    text = TARGET.read_text(encoding="utf-8")
    if SCAN_START in text and SCAN_END in text:
        before, rest = text.split(SCAN_START, 1)
        _old, after = rest.split(SCAN_END, 1)
        text = before.rstrip() + "\n" + after.lstrip()
    elif SCAN_START in text or SCAN_END in text:
        raise SystemExit("حد واحد لدفعة B12B موجود دون الآخر")
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    rows, families = {}, {}
    for ordinal in WINDOW:
        row = con.execute(
            "select entry_id,headword,pos,gloss from entries where entry_id glob ?",
            (f"kaikki_aramaic:{ordinal}:*",),
        ).fetchone()
        if row is None:
            raise SystemExit(f"مدخل مفقود: {ordinal}")
        rows[ordinal] = row
        family = con.execute(
            "select family_id from family_members where entry_id=?", (row["entry_id"],)
        ).fetchone()
        if family is None:
            raise SystemExit(f"أسرة مفقودة: {ordinal}")
        families[ordinal] = family["family_id"]
    con.close()
    lines = [
        SCAN_START, "",
        "## دفعة الجرد الآرامية أ 12B: آخر خمسين عضوًا من النافذة الرابعة", "",
        "- بيان النطاق، الخطوة 14: 50 عضوًا متتاليًا من الرتبة المصدرية 1062 إلى 1013. الموجب الكامل يثبت أعلاه، وغير الصادر يسجل بسبب واحد دون اختلاق إغلاق.", "",
    ]
    positive_ordinals = {item.ordinal for item in POSITIVES}
    for rank, ordinal in enumerate(WINDOW, 51):
        if ordinal in positive_ordinals:
            continue
        row = rows[ordinal]
        lines.append(
            f"- الرتبة {rank}: `{families[ordinal]}`؛ `{row['entry_id']}`؛ "
            f"{row['headword']}، {row['pos']}، «{row['gloss']}». "
            f"عائق: النوع=OPEN-CANDIDATE؛ يتطلب={PARKED[ordinal]}؛ الحكم (استكشاف): غير صادر."
        )
    lines.extend([
        "", "- حصيلة B12B: صلات موجبة جديدة=4؛ إغلاق=0؛ غير صادر=46.",
        "- حصيلة B12 كاملة: صلات موجبة جديدة=10؛ إغلاق=0؛ غير صادر=90.", "",
        SCAN_END, "",
    ])
    TARGET.write_text(text.rstrip() + "\n\n" + "\n".join(lines), encoding="utf-8", newline="\n")


