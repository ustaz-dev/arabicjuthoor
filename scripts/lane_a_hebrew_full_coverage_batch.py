def strip_own_block(text: str, start: str, end: str) -> str:
    if start not in text:
        return text
    before, rest = text.split(start, 1)
    if end not in rest:
        raise ValueError("بداية كتلة التغطية موجودة بلا علامة نهاية")
    _, after = rest.split(end, 1)
    return before.rstrip() + "\n" + after.lstrip()


def covered_entry_ids(text: str) -> set[str]:
    """Count members named by a real card or the machine registry."""

    headers = list(CARD_HEADER_RE.finditer(text))
    covered: set[str] = set()
    covered_source_lines: set[int] = set()
    for index, header in enumerate(headers):
        end = (
            headers[index + 1].start()
            if index + 1 < len(headers)
            else len(text)
        )
        section = text[header.start() : end]
        live_lines = re.findall(
            r"^- (?:الحكم \(استكشاف\)|عائق):.*$",
            section,
            re.MULTILINE,
        )
        for line in live_lines:
            covered.update(ENTRY_RE.findall(line))
            covered.update(HTML_ENTRY_RE.findall(line))
            covered_source_lines.update(
                int(value)
                for value in ENTRY_SOURCE_LINE_RE.findall(line)
            )
    if covered_source_lines:
        connection = sqlite3.connect(DB)
        try:
            for (entry_id,) in connection.execute(
                "SELECT entry_id FROM entries WHERE language='hebrew'"
            ):
                if entry_source_line(str(entry_id)) in covered_source_lines:
                    covered.add(str(entry_id))
        finally:
            connection.close()
    covered.update(issued_entry_ids_from_text(text, "hebrew"))
    covered.update(coverage_entry_ids("hebrew"))
    connection = sqlite3.connect(DB)
    try:
        inventory_ids = {
            str(entry_id)
            for (entry_id,) in connection.execute(
                "SELECT entry_id FROM entries WHERE language='hebrew'"
            )
        }
    finally:
        connection.close()
    covered.intersection_update(inventory_ids)
    return covered


def entry_source_line(entry_id: str) -> int:
    return int(entry_id.split(":", 2)[1])


def code_entry_id(entry_id: str) -> str:
    if "`" in entry_id:
        return f"<code>{entry_id}</code>"
    return f"`{entry_id}`"


def load_witnesses() -> tuple[list[str], dict[str, list[dict[str, Any]]]]:
    document = json.loads(WITNESSES.read_text(encoding="utf-8"))
    family_order: list[str] = []
    by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in document["witnesses"]:
        if row.get("stratum") != "biblical":
            continue
        family_id = str(row["family_id"])
        by_family[family_id].append(row)
        if family_id not in family_order:
            family_order.append(family_id)
    return family_order, by_family


def load_cohort(
    base_text: str,
) -> tuple[list[dict[str, Any]], dict[str, list[dict[str, Any]]]]:
    covered = covered_entry_ids(base_text)
    family_order, witnesses = load_witnesses()
    connection = sqlite3.connect(DB)
    connection.row_factory = sqlite3.Row
    selected: list[dict[str, Any]] = []
    chosen_families = 0
    try:
        for family_id in family_order:
            family = connection.execute(
                "SELECT * FROM families WHERE family_id=?",
                (family_id,),
            ).fetchone()
            if family is None:
                raise ValueError(f"الأسرة غائبة من الجرد: {family_id}")
            members = [
                dict(row)
                for row in connection.execute(
                    """
                    SELECT e.*,fm.role,fm.link_types_json
                    FROM family_members AS fm
                    JOIN entries AS e USING(entry_id)
                    WHERE fm.family_id=?
                    ORDER BY
                      CAST(
                        substr(e.entry_id,instr(e.entry_id,':')+1)
                        AS INTEGER
                      ),
                      e.entry_id
                    """,
                    (family_id,),
                )
            ]
            uncovered = [
                member
                for member in members
                if member["entry_id"] not in covered
            ]
            if not uncovered:
                continue
            chosen_families += 1
            for member in uncovered:
                candidates = [
                    dict(row)
                    for row in connection.execute(
                        """
                        SELECT kind,form,status,rule_ids_json,route_flag
                        FROM candidates
                        WHERE entry_id=? AND kind IN ('root','core')
                        ORDER BY kind,route_flag,status,form,rule_ids_json
                        """,
                        (member["entry_id"],),
                    )
                ]
                own_witnesses = [
                    row
                    for row in witnesses[family_id]
                    if row["entry_id"] == member["entry_id"]
                ]
                selected.append(
                    {
                        **member,
                        "family_id": family_id,
                        "family_anchor": family["anchor_headword"],
                        "family_member_count": family["member_count"],
                        "family_construction": family["construction"],
                        "candidates": candidates,
                        "own_witnesses": own_witnesses,
                        "family_witness": witnesses[family_id][0],
                    }
                )
            if chosen_families >= FAMILY_LIMIT:
                break
    finally:
        connection.close()
    return selected, witnesses


def remaining_family_counts(
    covered: set[str],
) -> tuple[int, int]:
    """Return Biblical-priority and whole-Hebrew families still uncovered."""

    biblical_order, _ = load_witnesses()
    connection = sqlite3.connect(DB)
    try:
        members_by_family: dict[str, list[str]] = defaultdict(list)
        for family_id, entry_id in connection.execute(
            """
            SELECT f.family_id,fm.entry_id
            FROM families AS f
            JOIN family_members AS fm USING(family_id)
            WHERE f.language='hebrew'
            ORDER BY f.family_id,fm.entry_id
            """
        ):
            members_by_family[str(family_id)].append(str(entry_id))
        whole_remaining = sum(
            any(entry_id not in covered for entry_id in members)
            for members in members_by_family.values()
        )
        biblical_remaining = sum(
            any(
                entry_id not in covered
                for entry_id in members_by_family[family_id]
            )
            for family_id in biblical_order
        )
        return biblical_remaining, whole_remaining
    finally:
        connection.close()


def loan_route(
    entry: dict[str, Any],
) -> tuple[str, str, bool] | None:
    """Classify only an explicitly named donor route.

    Mere comparison or cognacy language never closes a member.  External
    donors take precedence over an intermediate Semitic donor, because a
    route such as Aramaic < Iranian is still external to the Semitic house.
    """

    etymology = one_line(entry["etymology"])
    lower = etymology.lower()
    transfer_words = (
        "borrowed from",
        "borrowing",
        "ultimately from",
        "of akkadian origin",
        "of aramaic origin",
    )
    if not any(token in lower for token in transfer_words):
        return None

    external_donors = (
        "egyptian",
        "greek",
        "latin",
        "persian",
        "iranian",
        "median",
        "sumerian",
        "german",
        "yiddish",
        "english",
        "french",
        "dutch",
        "sanskrit",
        "tamil",
        "elamite",
        "armenian",
    )
    if any(donor in lower for donor in external_donors):
        return (
            "LOANWORD",
            "مسار اقتراض خارجي مصرح به في حقل التأثيل: "
            f"{etymology}",
            True,
        )

    semitic_donors = (
        "aramaic",
        "akkadian",
        "syriac",
        "ugaritic",
        "phoenician",
    )
    if any(donor in lower for donor in semitic_donors):
        return (
            "INTRA-HOUSE-TRANSFER",
            "انتقال داخل البيت السامي بمانح مسمى في حقل التأثيل: "
            f"{etymology}",
            True,
        )
    return None


def classify(entry: dict[str, Any]) -> tuple[str, str, bool]:
    """Return state, reason, and whether the state is terminal."""

    entry_id = str(entry["entry_id"])
    if entry_id in POSITIVE_SPECS and entry["own_witnesses"]:
        return POSITIVE_SPECS[entry_id]["verdict"], "صلة موجبة مسندة", False
    if bool(entry["form_of"]) or entry["role"] == "form":
        return (
            "FORM-OF-ISOLATED",
            "صورة صرفية منشورة لمدخل آخر؛ لا ترث حكم الأم",
            True,
        )
    gloss = str(entry["gloss"] or "").lower()
    if entry["role"] == "alternative" and "spelling of" in gloss:
        return (
            "FORM-OF-ISOLATED",
            "رسم بديل مصرح بأنه صورة لمدخل آخر؛ لا يرث حكمه",
            True,
        )
    if entry["pos"] == "name":
        return (
            "PROPER-NAME-ISOLATED",
            "علم مصرح به في حقل الصنف؛ يعزل عن المقارنة المعجمية",
            True,
        )
    if entry["role"] == "alternative" and (
        "acronym" in gloss or "abbreviation" in gloss
    ):
        return (
            "ABBREVIATION",
            "اختصار مصرح به، لا مدخل جذري مستقل",
            True,
        )
    named_loan_route = loan_route(entry)
    if named_loan_route is not None:
        return named_loan_route
    if "calque" in str(entry["etymology"] or "").lower():
        return (
            "LOAN-ROUTE-ISOLATED",
            "ترجمة اقتراضية ذات مانح أجنبي مسمى في حقل التأثيل",
            True,
        )
    if entry["pos"] in {"prep", "pron"}:
        return (
            "FUNCTION-WORD",
            "أداة نحوية أو ضمير؛ يعزل عن حكم الجذر المعجمي في هذه الجولة",
            True,
        )

    custom = {
        "kaikki_hebrew:6:en-ארץ-he-noun-eo~xhRN5": (
            "LAW-GAP",
            "أرض العربية مطابقة معنى في مروحة قديمة، لكن انعكاس "
            "`*ṣ́` إلى צ العبرية بإزاء ض العربية لا يملك صفا موقعا؛ "
            "`DENT-08` خاص بالظاء ولا يمدد",
        ),
        "kaikki_hebrew:124:en-ים-he-noun-SmnxnIwm": (
            "OPEN-CANDIDATE",
            "يم العربية يطابق البحر في مصدرين قديمين، لكن لسان العرب "
            "ينقل دعوى تعريبها من السريانية؛ يلزم حسم مسار عمق القرض",
        ),
        "kaikki_hebrew:62:en-מקל-he-noun-EdDa-0Wy": (
            "OPEN-CANDIDATE",
            "المصدر يقول Unknown وLikely related إلى مقلاب النجدية؛ "
            "لم يثبت اللفظ المقابل نفسه في مصدرين عربيين قديمين",
        ),
        "kaikki_hebrew:237:en-אלון-he-noun-34d2RUBH": (
            "SOURCE-GAP",
            "التأثيل نفسه متردد بين صورة كنعانية أصلية واقتراض أكادي؛ "
            "لا يصدر حكم قبل فصل السلسلتين",
        ),
        "kaikki_hebrew:900:en-עפר-he-noun-l~u2f1Wi": (
            "OPEN-CANDIDATE",
            "عفر العربية يطابق التراب، لكن المصدر يسمي احتمال "
            "انتقالها من الآرامية؛ يلزم تطبيق قاعدة عمق القرض وإحالة "
            "السلسلة إلى زوج المانح قبل إصدار حكم عبري مستقل",
        ),
        "kaikki_hebrew:927:en-מראה-he-noun-ujBBkyy1": (
            "LAW-GAP",
            "مرأى ومرآة العربية يطابقان sight وappearance، لكن "
            "الجذر العبري ראה والجذر العربي رأي يختلفان في الرجل "
            "الضعيفة ولا صف صرفي موقع لهذه المقابلة",
        ),
    }
    if entry["entry_id"] in custom:
        state, reason = custom[entry["entry_id"]]
        return state, reason, False
    if not entry["own_witnesses"]:
        return (
            "SOURCE-GAP",
            "لا شاهد توراتي صريح للعضو نفسه؛ شاهد رأس الأسرة لا يورثه القدم",
            False,
        )
    if any(
        token in str(entry["etymology"] or "")
        for token in ("Unknown", "Uncertain", "possibly", "Likely")
    ):
        return (
            "SOURCE-GAP",
            "حقل التأثيل يحمل عدم يقين صريحا في أصل العضو أو مساره",
            False,
        )
    return (
        "OPEN-CANDIDATE",
        "للعضو شاهد توراتي، لكن لم يجتمع بعد مقابل عربي مرخص "
        "ومروحة معنى من مصدرين قديمين",
        False,
    )


def oldest_form(entry: dict[str, Any]) -> str:
    if entry["own_witnesses"]:
        witness = entry["own_witnesses"][0]
        proto = one_line(entry["etymology"])
        proto_note = f"؛ الأصل المنشور={proto}" if proto else ""
        stratum = {
            "biblical": "توراتي",
            "mishnaic": "مِشْناوي",
            "other-referenced": "مرجع مؤرخ آخر",
        }.get(str(witness.get("stratum", "")), "مرجع صريح")
        return (
            f"طبقة={stratum}؛ الأساس الزمني=شاهد صريح للعضو نفسه؛ "
            f"الإحالة={one_line(witness['reference'])}{proto_note}"
        )
    family = entry.get("family_witness")
    if family is None:
        return (
            "لا شاهد زمني صريح للعضو نفسه ولا لمرساة الأسرة في ملف "
            "الشواهد؛ حفظ سطر المصدر المعجمي ولم يخترع قدم"
        )
    return (
        "لا شاهد زمني صريح للعضو نفسه؛ مرساة الأسرة "
        f"`{entry['family_anchor']}` مشهودة في "
        f"{one_line(family['reference'])}، ولا يورثها هذا العضو"
    )


def zero_step(entry: dict[str, Any]) -> str:
    if bool(entry["form_of"]) or entry["role"] == "form":
        targets = one_line(entry["form_targets_json"])
        return (
            "حفظت الصورة الصرفية كما هي؛ حقل form_of يربطها "
            f"بهدفه المنشور `{targets}`، ولم تنزع الزيادة ولم يرث "
            "العضو حكم الهدف"
        )
    return (
        "حفظ الرسم السطحي الكامل للعضو؛ لا تعرية ولا رد إلى رأس "
        "الأسرة ولا وراثة عبر مركب أو متجانس"
    )


def candidate_summary(entry: dict[str, Any]) -> str:
    if not entry["candidates"]:
        return "لا مسار مرشح مسجل لهذا العضو في الجرد"
    pieces: list[str] = []
    for row in entry["candidates"][:6]:
        rules = ",".join(json.loads(row["rule_ids_json"])) or "مباشر"
        pieces.append(
            f"{row['kind']} `{row['form']}` "
            f"({row['status']}؛ {rules}؛ route={row['route_flag']})"
        )
    return "؛ ".join(pieces)


