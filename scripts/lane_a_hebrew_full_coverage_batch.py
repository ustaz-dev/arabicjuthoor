def one_line(value: Any) -> str:
    return (
        " ".join(str(value or "").split())
        .replace("`", "'")
        .replace("—", "،")
    )


def atomic_write(path: Path, text: str) -> None:
    text = unicodedata.normalize("NFC", text)
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp_name = tempfile.mkstemp(
        prefix=path.name + ".",
        suffix=".tmp",
        dir=path.parent,
        text=True,
    )
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temp_name, path)
    except Exception:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass
        raise


def load_coverage_rows() -> dict[str, dict[str, Any]]:
    """Load the one-row-per-member machine coverage registry."""

    rows: dict[str, dict[str, Any]] = {}
    if not COVERAGE.exists():
        return rows
    for line_number, raw_line in enumerate(
        COVERAGE.read_text(encoding="utf-8").splitlines(),
        1,
    ):
        if not raw_line.strip():
            continue
        row = json.loads(raw_line)
        entry_id = str(row.get("member_id", ""))
        if not entry_id:
            raise ValueError(f"سطر تغطية بلا معرف: {line_number}")
        if entry_id in rows:
            raise ValueError(f"معرف تغطية مكرر: {entry_id}")
        rows[entry_id] = row
    return rows


def coverage_entry_ids(language: str) -> set[str]:
    return {
        entry_id
        for entry_id, row in load_coverage_rows().items()
        if row.get("language") == language
    }


def issued_entry_ids_from_text(text: str, language: str) -> set[str]:
    """Recover member IDs from explicit issued-result lines."""

    source_line_re = re.compile(rf"kaikki_{language}:(\d+):")
    issued_source_lines: set[int] = set()
    for line in text.splitlines():
        if ISSUED_FIELD_RE.search(line) or ISSUED_MEMBER_RESULT_RE.search(line):
            issued_source_lines.update(
                int(value) for value in source_line_re.findall(line)
            )

    if not issued_source_lines:
        return set()
    connection = sqlite3.connect(DB)
    try:
        return {
            str(entry_id)
            for (entry_id,) in connection.execute(
                "SELECT entry_id FROM entries WHERE language=?",
                (language,),
            )
            if int(str(entry_id).split(":", 2)[1]) in issued_source_lines
        }
    finally:
        connection.close()


def coverage_row(
    entry: dict[str, Any],
    language: str,
    state: str,
    reason: str,
    batch_number: str,
) -> dict[str, str]:
    return {
        "member_id": str(entry["entry_id"]),
        "language": language,
        "orthography": one_line(entry["headword"]),
        "branch_meaning": one_line(entry["gloss"]),
        "nonissuance_reason": f"{state}: {one_line(reason)}",
        "batch_number": batch_number,
    }


def write_coverage_updates(
    pending_rows: list[dict[str, str]],
    terminal_entry_ids: set[str],
) -> None:
    """Upsert pending rows and remove rows superseded by final outcomes."""

    rows = load_coverage_rows()
    for entry_id in terminal_entry_ids:
        rows.pop(entry_id, None)
    for row in pending_rows:
        entry_id = row["member_id"]
        if entry_id in terminal_entry_ids:
            raise ValueError(
                f"العضو محكوم ومسجل بلا حكم في الدفعة نفسها: {entry_id}"
            )
        rows[entry_id] = row

    language_order = {"hebrew": 0, "aramaic": 1}

    def sort_key(item: tuple[str, dict[str, Any]]) -> tuple[int, int, str]:
        entry_id, row = item
        try:
            source_line = int(entry_id.split(":", 2)[1])
        except (IndexError, ValueError):
            source_line = 2**31
        return (
            language_order.get(str(row.get("language")), 99),
            source_line,
            entry_id,
        )

    text = "\n".join(
        json.dumps(row, ensure_ascii=False, separators=(",", ":"))
        for _, row in sorted(rows.items(), key=sort_key)
    )
    atomic_write(COVERAGE, text + ("\n" if text else ""))


