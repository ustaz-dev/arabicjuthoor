def sound_path(row: dict, decision: Decision) -> str:
    special = SPECIAL_SOUND.get(str(row["branch"]))
    return special if special is not None else ORIGINAL_SOUND_PATH(row, decision)


def select_rows() -> tuple[list[tuple[int, dict]], list[tuple[int, dict]]]:
    hebrew = R3.nonduplicates("hebrew")
    aramaic = R3.nonduplicates("aramaic")
    chosen = hebrew[:100]
    assert len(DECISIONS) == 100
    assert len(chosen) == 100
    assert chosen[0][0] == 902 and chosen[-1][0] == 1179
    assert chosen[49][0] == 1075 and chosen[50][0] == 1079
    assert not aramaic, f"Aramaic inventory changed: {aramaic[:3]}"
    return chosen, aramaic


def render_card(serial: int, index: int, row: dict, decision: Decision,
                arabic_matches: dict[str, list[dict]]) -> str:
    R3.choose_lexicon_entry = choose_lexicon_entry
    R3.sound_path = sound_path
    card = R3.render_card(serial, index, row, decision, arabic_matches)
    old_batch = 3 if serial <= 50 else 4
    new_batch = 7 if serial <= 50 else 8
    card = card.replace(
        f"WO-C-HEBREW-{old_batch:03d}-",
        f"WO-C-HEBREW-{new_batch:03d}-",
        1,
    )
    zero = SPECIAL_ZERO.get(str(row["branch"]))
    if zero:
        card = re.sub(
            r"^- الخطوةُ صفر \(التعرية بصرف الفرع\): .*$",
            f"- الخطوةُ صفر (التعرية بصرف الفرع): {zero}.",
            card,
            count=1,
            flags=re.M,
        )
    if decision.verdict == "ABBREVIATION":
        card = card.replace(
            "الاختصار ليس جذرًا معجميًا؛ عُزل قبل أن يرث حكم خذل لمجرد الرسم.",
            "الاختصار ليس جذرًا معجميًا؛ عُزل قبل أن يرث حكم دق لمجرد الرسم.",
        )
    if row["branch"] == "לכם":
        card = re.sub(
            r"^- أقدمُ صورةٍ مستعادة: .*$",
            "- أقدمُ صورةٍ مستعادة: لم يرجع فهرس قاموس الفرع مدخلة؛ حفظ صف المسح للتشخيص ولم يُستعمل مصدرًا يغلق البطاقة.",
            card,
            count=1,
            flags=re.M,
        )
        card = card.replace(
            "- إشعاع الأسرة في الفرع: المداخل المقروءة=1؛ المختار=1.",
            "- إشعاع الأسرة في الفرع: المداخل المقروءة=0؛ المختار=0؛ فجوة المصدر مسماة.",
        )
    size = len(card.encode("utf-8"))
    assert size <= R3.MAX_CARD_BYTES, f"Round-five card is {size} bytes"
    return card


def render_batches() -> tuple[str, dict]:
    chosen, aramaic = select_rows()
    roots = {R3.AR.normalize_root(decision.candidate) for decision in DECISIONS}
    arabic_matches = R3.AR.matches_for_roots(R3.AR.DEFAULT_RESOURCES, roots, None)
    cards = [
        render_card(serial, index, row, decision, arabic_matches)
        for serial, ((index, row), decision) in enumerate(zip(chosen, DECISIONS), 1)
    ]
    batches: list[str] = []
    for batch_number, start in ((7, 0), (8, 50)):
        batch = cards[start:start + 50]
        batches += [
            f"## الدفعة العبرية {batch_number}: الجولة الخامسة من حوض both (2026-08-16)",
            "",
            ("الحالة: طبقة الاستكشاف؛ إلحاق فقط. اختيرت أول خمسين صورة غير مكررة "
             "من الذاكرة بترتيب `overlap` النازل، وكل بطاقة منتهية بحكم."),
            "",
        ]
        for offset, card in enumerate(batch, 1):
            batches.append(card.rstrip())
            batches.append("")
            if offset % 5 == 0:
                batches.append(
                    f"<!-- LANE-C-HEBREW-R5-B{batch_number}-CHUNK-{offset // 5:03d}:END -->")
                batches.append("")
    appendix = "\n".join(batches).rstrip() + f"\n\n<!-- {MARKER}:END -->\n"
    after_memory = HEBREW.read_text(encoding="utf-8") + "\n" + appendix
    hebrew_remaining_after = 0
    for row in R3.load_rows("hebrew"):
        branch = str(row["branch"])
        if branch in after_memory:
            continue
        hebrew_remaining_after += 1
        after_memory += "\n" + branch
    verdicts = collections.Counter(decision.verdict for decision in DECISIONS)
    states = collections.Counter(
        decision.state or ("READY" if decision.verdict == R else decision.verdict)
        for decision in DECISIONS
    )
    diagnostics = {
        "hebrew_remaining_before": len(R3.nonduplicates("hebrew")),
        "hebrew_remaining_after": hebrew_remaining_after,
        "aramaic_rows": len(R3.load_rows("aramaic")),
        "aramaic_remaining": len(aramaic),
        "first": chosen[0][0],
        "batch1_last": chosen[49][0],
        "batch2_first": chosen[50][0],
        "last": chosen[-1][0],
        "verdicts": dict(sorted(verdicts.items())),
        "states": dict(sorted(states.items())),
        "appendix_bytes": len(appendix.encode("utf-8")),
        "max_card_bytes": max(len(card.encode("utf-8")) for card in cards),
        "card_count": len(cards),
        "branch_source_gaps": sum("لم يرجع فهرس قاموس الفرع مدخلة" in card for card in cards),
    }
    return appendix, diagnostics


