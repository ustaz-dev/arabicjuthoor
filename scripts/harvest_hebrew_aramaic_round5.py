    """Expose the single missing source row instead of silently skipping it."""
    if row["branch"] == "לכם":
        pseudo = {
            "word": row["branch"],
            "read": str(row["say"]).split("  (")[0],
            "en": row["gloss"],
            "etym": "",
        }
        return pseudo, [pseudo], "فشل فهرس قاموس الفرع؛ استعمل صف المسح للتشخيص فقط"
    return ORIGINAL_LOOKUP(row)


