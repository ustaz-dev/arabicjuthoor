# والعبريّةِ تنتهي بواحدةٍ منها، ومنها `מלכותא` التي لا تبلغُ `ملك`، و`אלהין`
# التي لا تبلغُ `إله`.
#
# **ولا تُحسَمُ الكلمةُ بل تُفتَحُ:** يُولَّدُ هيكلٌ بديلٌ موسومٌ ويُقابَلُ مع الأصلِ
# كليهما، فمَن رأى العلامةَ أصلًا في كلمةٍ بعينِها ردَّ البديلَ بحجّتِه.
# **تُكتَبُ بالحرفِ غيرِ الختاميِّ عمدًا**: الهيكلُ يُطبِّعُ الختاميَّ إلى أصلِه
# (ן إلى נ و ם إلى מ) قبلَ هذه المقابلة، فمن كتبَها بالختاميِّ لم يلتقطْ شيئًا.
# وقد ضاعَت `אלהין` بهذا حتّى صُحِّح.
NORTH_ENDINGS = [
    ("ותא", "جمعُ المؤنّثِ المعرَّفِ أو المصدرُ المعرَّف"),
    ("יתא", "تاءُ التأنيثِ المعرَّفةُ بعدَ ياء"),
    ("תא", "تاءُ التأنيثِ مع ألفِ التعريف"),
    ("יא", "جمعُ المذكّرِ المعرَّف"),
    ("ות", "جمعُ المؤنّثِ أو المصدر"),
    ("ימ", "جمعُ المذكّرِ العبريّ"),
    ("ינ", "جمعُ المذكّرِ الآراميّ"),
    ("ה", "هاءُ التأنيثِ العبريّة"),
    ("ת", "تاءُ التأنيثِ المضافة"),
    # **ضميرُ الغائبِ المضافُ في آخرِ الكلمة**، وهو أكثرُ ما رُصِدَ في مادّةِ
    # منصورٍ بعدَ حروفِ المدّ: `זרעו` تُقرَأُ «زرعه» و`בו` تُقرَأُ «به»،
    # 1,882 شاهدًا. وليس صامتًا من الجذرِ فلا يدخلُ الهيكل.
    ("ו", "ضميرُ الغائبِ المضاف"),
]
WEAK = "והי"

# ------------------------------------------------- صرفُ المصريّةِ وصدرُها السببيّ
# **الدرسُ منقولٌ من مادّةِ منصور.** لمّا استُخرِجَت استثناءاتُ مصفوفتِه كان
# أكثرُها الثلاثةُ **صرفًا لا صوتًا**: واوُ المدِّ 1,913، وضميرُ الغائبِ 1,882،
# وميمةُ الجمعِ 1,739. فالذي يُفسِدُ الهيكلَ في الأخواتِ الشماليّاتِ ليس إبدالًا
# مجهولًا بل لاصقةٌ معروفةٌ تُحسَبُ حرفًا أصليًّا. والمصريّةُ مثلُها سواء.
#
# **والقدرُ مقيسٌ في مخزنِنا لا مقدَّر**: من 2,341 صورةً مصريّةً متمايزةً
# تحملُ 370 تاءَ تأنيثٍ (15.8%)، و293 سينَ سببيّةٍ في الصدر (12.5%)، ثمّ
# الجمعُ والمثنّى والنسبةُ دونَها. أي أنّ **أكثرَ من خُمسِ المادّةِ** كان
# يدخلُ المروحةَ بحرفٍ زائدٍ يُطلَبُ له مقابلٌ عربيٌّ لا وجودَ له.
#
# **ولا يُحذَفُ شيء، بل يُزادُ بديلٌ موسومٌ** كما في `north_skeletons`: الصورةُ
# كما وردَت تبقى أوّلَ الهياكلِ دائمًا، لأنّ التاءَ قد تكونُ أصلًا (`ḫt` الخشب)
# والسينُ قد تكونُ أصلًا (`sn` الأخ). والمعنى هو الذي يفصل.
EGYPTIAN_ENDINGS = [
    ("wt", "جمعِ المؤنّث"),
    ("wy", "المثنّى"),
    ("ty", "نسبةِ المؤنّثِ أو المثنّى"),
    ("w", "جمعِ المذكّر"),
    ("t", "تاءِ التأنيث"),
    ("y", "ياءِ النسبة"),
    ("j", "ياءِ النسبة"),
]


def egyptian_skeletons(letters: list[str]) -> list[tuple[list[str], str]]:
    """هياكلُ الصورةِ المصريّةِ بأوسامِها، والأوّلُ «كما وردَت» دائمًا."""
    out: list[tuple[list[str], str]] = []
    seen: set[str] = set()

    def add(seq: list[str], label: str) -> None:
        key = "".join(seq)
        if len(seq) < 2 or key in seen:
            return
        seen.add(key)
        out.append((seq, label))

    add(list(letters), "كما وردَت")
    for end, why in EGYPTIAN_ENDINGS:
        if len(letters) - 1 >= 2 and letters[-1] == end:
            add(letters[:-1], f"بإسقاطِ {why} ({end})")
            break
        if len(end) == 2 and len(letters) - 2 >= 2 and letters[-2:] == list(end):
            add(letters[:-2], f"بإسقاطِ {why} ({end})")
            break
    # **صدرُ السببيّةِ س**: `s-ḏm` «يُسمِعُ» من `ḏm`، وهي أطردُ زيادةٍ في
    # صدرِ الفعلِ المصريّ. ولا تُنزَعُ إلّا إذا بقيَ بعدَها هيكلٌ صالحٌ.
    if len(letters) >= 4 and letters[0] in ("s", "š"):
        add(letters[1:], "بإسقاطِ سينِ السببيّةِ من الصدر")
    return out


def latin_stem_skeletons(word: str, script: str = "latin") -> list[tuple[list[str], str]]:
    """هياكلُ الكلمةِ اللاتينيّةِ الأصلِ بأوسامِها، والأوّلُ «كما وردَت» دائمًا.

    تُنزَعُ الزوائدُ ما دامَ الهيكلُ مجاوِزًا الأربعةَ، ولا يُنزَعُ شيءٌ يترُكُ
    ساقًا أقصرَ من حرفَينِ صامتَين. والعبارةُ ذاتُ الكلمتَينِ تُفَضُّ كلماتٍ.
    """
    out: list[tuple[list[str], str]] = []
    seen: set[str] = set()

    def add(text: str, label: str) -> None:
        s = skeleton(text, script)
        key = "".join(s)
        if not (2 <= len(s) <= 4) or key in seen:
            return
        seen.add(key)
        out.append((s, label))

    base = word.strip()
    add(base, "كما وردَت")

    # العبارةُ تُفَضُّ، فكلُّ كلمةٍ فيها مادّةٌ على حدة
    parts = re.split(r"[\s'’-]+", base)
    if len(parts) > 1:
        for part in parts:
            if len(part) > 2:
                add(part, f"كلمةُ «{part}» من العبارة")
        return out

    stem, peeled = base, []
    for _ in range(3):
        low = stem.lower()
        cut = next((e for e in LATIN_DERIVATIONAL
                    if low.endswith(e) and len(low) - len(e) >= 3), None)
        if not cut:
            break
        stem, _ = stem[:-len(cut)], peeled.append(cut)
        add(stem, "بإسقاطِ زائدةِ " + " ثمّ ".join(f"`-{p}`" for p in peeled))
        if len(skeleton(stem, script)) <= 4:
            break

    low = base.lower()
    pre = next((p for p in LATIN_PREFIXES
                if low.startswith(p) and len(low) - len(p) >= 4), None)
    if pre:
        add(base[len(pre):], f"بإسقاطِ صدرِ `{pre}-`")
        if peeled:
            add(stem[len(pre):] if stem.lower().startswith(pre) else stem,
                f"بإسقاطِ صدرِ `{pre}-` وزائدةِ النهاية")
    return out


