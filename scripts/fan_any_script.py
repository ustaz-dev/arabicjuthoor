# **العطبُ الذي تُغلِقُه (بقرارِ المؤلّفِ 2026-08-10):** الأداةُ تُسقِطُ الألفَ
# النهائيّةَ وحدَها، فتبقى تاءُ التأنيثِ في `עסקתא` حرفًا رابعًا في الهيكلِ ولا
# تُبلَغُ `عسق`. قالَ المؤلّف: «من السهلِ الواضحِ أن تنزعَ الـ ta من الكلمةِ لتراها
# أحسن». وهي الفصيلةُ نفسُها التي رُئيَت في لاحقةِ `*-tḗr` وفي سينِ الرفعِ في
# `rēx`: **صرفٌ يُحسَبُ أصلًا.** ومَسُّها هنا أوسعُ: 525 بطاقةً في الآراميّةِ
# والعبريّةِ تنتهي بواحدةٍ منها، ومنها `מלכותא` التي لا تبلغُ `ملك`، و`אלהין`
# التي لا تبلغُ `إله`.
#
# **ولا تُحسَمُ الكلمةُ بل تُفتَحُ:** يُولَّدُ هيكلٌ بديلٌ موسومٌ ويُقابَلُ مع الأصلِ
# كليهما، فمَن رأى العلامةَ أصلًا في كلمةٍ بعينِها ردَّ البديلَ بحجّتِه.
# **تُكتَبُ بالحرفِ غيرِ الختاميِّ عمدًا**: الهيكلُ يُطبِّعُ الختاميَّ إلى أصلِه
# (ן إلى נ و ם إلى מ) قبلَ هذه المقابلة، فمن كتبَها بالختاميِّ لم يلتقطْ شيئًا.
# وقد ضاعَت `אלהין` بهذا حتّى صُحِّح.
NORTH_ENDINGS = [
    ("ותא", "جمعُ المؤنّثِ المعرَّفِ أو المصدرُ المعرَّف"),
    ("יתא", "تاءُ التأنيثِ المعرَّفةُ بعدَ ياء"),
    ("תא", "تاءُ التأنيثِ مع ألفِ التعريف"),
    ("יא", "جمعُ المذكّرِ المعرَّف"),
    ("ות", "جمعُ المؤنّثِ أو المصدر"),
    ("ימ", "جمعُ المذكّرِ العبريّ"),
    ("ינ", "جمعُ المذكّرِ الآراميّ"),
    ("ה", "هاءُ التأنيثِ العبريّة"),
    ("ת", "تاءُ التأنيثِ المضافة"),
]
WEAK = "והי"


def _north_letters(word: str) -> str:
    w = unicodedata.normalize("NFC", str(word)).strip()
    w = w.translate(_DIAC_HEB).translate(FINALS)
    return re.sub(r"[^א-ת]", "", w)


def north_skeletons(word: str) -> list[tuple[list[str], str]]:
    """هياكلُ الكلمةِ الشماليّةِ كلُّها بأوسامِها، والأوّلُ هو «كما وردَت».

    وتُفتَحُ جبهتانِ لا واحدة: **علامةُ الحالِ والجمع**، و**الحرفُ العلّةُ** الذي
    تُسقِطُه القاعدةُ الحاليّةُ بلا استثناء. فالهاءُ في `אלהין` جذريّةٌ (إله) وقد
    أسقطَتها القاعدةُ، والياءُ في `ביתא` جذريّةٌ (بيت) وقد أسقطَتها.
    """
    base = _north_letters(word)
    if len(base) > 2 and base.endswith("א"):
        base = base[:-1]          # ألفُ التعريفِ الآراميّة، بقرارِ المؤلّف
    out: list[tuple[list[str], str]] = []
    seen: set[str] = set()

    def add(letters: str, label: str) -> None:
        if len(letters) < 2 or letters in seen:
            return
        seen.add(letters)
        out.append((list(letters), label))

    def drop_weak(s: str) -> str:
        return s[0] + "".join(c for c in s[1:] if c not in WEAK) if len(s) > 2 else s

    add(drop_weak(base), "كما وردَت")
    add(base, "بإبقاءِ حرفِ العلّةِ أصلًا")
    for end, why in NORTH_ENDINGS:
        if base.endswith(end) and len(base) - len(end) >= 2:
            stem = base[:-len(end)]
            add(drop_weak(stem), f"بإسقاطِ {why} ({end})")
            add(stem, f"بإسقاطِ {why} ({end}) وإبقاءِ حرفِ العلّة")
            break
    return out


def skeleton(word: str, script: str | None = None) -> list[str]:
    """الهيكلُ الصامتيُّ كقائمةِ حروفٍ يُبنى عليها التوليد."""
    w = unicodedata.normalize("NFC", str(word)).strip()
    script = script or detect(w)

    if script == "north":
        w = w.translate(_DIAC_HEB).translate(FINALS)
        w = re.sub(r"[^א-ת]", "", w)
        if len(w) > 2 and w.endswith("א"):
            w = w[:-1]
        if len(w) > 2:
            w = w[0] + "".join(c for c in w[1:] if c not in "והי")
        return list(w)

    if script == "coptic":
        w = w.lower()
        return [c for c in w if c in COPTIC_FAN and c not in COPTIC_VOWELS]

    if script == "greek":
        base = unicodedata.normalize("NFD", w.lower())
        base = "".join(c for c in base if not unicodedata.combining(c))
        return [c for c in base if c in GREEK_FAN and c not in GREEK_VOWELS]

    if script == "gothic":
        return [c for c in w if c in GOTHIC_FAN and c not in GOTHIC_VOWELS]

    if script == "persian":
        # الصوائتُ الطويلةُ تُطرَحُ من غيرِ الحرفِ الأوّل، كما يُفعَلُ بالشمالِ الساميّ
        w = re.sub(r"[ً-ْـ‌]", "", w)
        w = re.sub(r"[^ء-ی]", "", w)
        if len(w) > 2 and w.endswith("ه"):
            w = w[:-1]
        if len(w) > 2:
            w = w[0] + "".join(c for c in w[1:] if c not in PERSIAN_VOWELS)
        return [c for c in w if c in PERSIAN_FAN]

    if script in {"latin", "germanic"}:
        # الصوائتُ تُطرَحُ والمقارنةُ على الهيكلِ الصامتيّ، والحرفانِ المزدوجانِ
        # يُقرآنِ صوتًا واحدًا قبلَ أن يُقرأَ كلُّ حرفٍ وحدَه
        base = unicodedata.normalize("NFD", w.lower())
        base = "".join(c for c in base if not unicodedata.combining(c) or c in "̧")
        base = base.replace("̧", "")
        out, i = [], 0
        while i < len(base):
            two = base[i:i + 2].upper()
            if two in LATIN_DIGRAPH:
                out.append(two)
                i += 2
                continue
            c = base[i]
            if c in LATIN_VOWELS:
                i += 1
                continue
            if c in LATIN_FAN:
                out.append(c)
            i += 1
        # الإدغامُ في الكتابةِ لا يُضاعِفُ الصامتَ في الهيكل
        return [c for i, c in enumerate(out) if i == 0 or c != out[i - 1]]

    if script == "egyptian":
        out, i = [], 0
        keys = sorted(EGYPTIAN_FAN, key=len, reverse=True)
        while i < len(w):
            for k in keys:
                if w[i:i + len(k)] == k:
                    out.append(k)
                    i += len(k)
                    break
            else:
                i += 1
        return out

    # الأكديّة: تُنزَعُ ميمةُ التنوينِ والصوائت
    w = AKKADIAN_MIMATION.sub("", w)
    out = []
    for c in w:
        if c in AKKADIAN_VOWELS:
            continue
        if c in AKKADIAN_FAN:
            out.append(c)
    # الإدغامُ في الرومنةِ لا يُضاعِفُ الصامت
    return [c for i, c in enumerate(out) if i == 0 or c != out[i - 1]]


FANS = {
    "north": NORTH_FAN, "coptic": COPTIC_FAN, "greek": GREEK_FAN,
    "egyptian": EGYPTIAN_FAN, "akkadian": AKKADIAN_FAN,
    "latin": LATIN_FAN, "gothic": GOTHIC_FAN, "germanic": GERMANIC_FAN,
    "persian": PERSIAN_FAN,
}


def fan(word: str, script: str | None = None, limit: int = 400,
        geminate: bool = True) -> list[str]:
    """مروحةُ المرشَّحاتِ العربيّةِ للكلمة.

    **والمضاعَفُ يدخلُ فيها** (`geminate`): الفرعُ يكتبُ الصامتَ مرّةً والعربيّةُ
    تُضاعِفُه في بابٍ كاملٍ من أبوابِها، فـ`asher` بإزاءِ `شرر` و`tcher` بإزاءِ
    `ذرر` و`tchet` بإزاءِ `ذدد`. ومن قصرَ الهيكلَ ذا الصامتَينِ على مرشَّحٍ من
    حرفَينِ أغلقَ بابَ المضاعَفِ كلَّه وهو **أوضحُ صورةٍ للنواةِ الثنائيّةِ في
    العربيّةِ نفسِها**، فالمادّةُ الثنائيّةُ إذا صارت جذرًا ثلاثيًّا كرَّرَت آخرَها.
    """
    script = script or detect(word)
    sk = skeleton(word, script)
    if not (2 <= len(sk) <= 4):
        return []
    table = FANS[script]
    options = [table.get(c, ()) for c in sk]
    if any(not o for o in options):
        return []
    out = ["".join(c) for c in itertools.islice(itertools.product(*options), limit)]
    if geminate and len(sk) == 2:
        seen = set(out)
        for w in list(out):
            g = w + w[-1]
            if g not in seen and len(out) < limit:
                seen.add(g)
                out.append(g)
    return out


