def detect(text: str) -> str:
    for ch in text:
        o = ord(ch)
        if 0x0590 <= o <= 0x05FF:
            return "north"
        if 0x2C80 <= o <= 0x2CFF or 0x03E2 <= o <= 0x03EF:
            return "coptic"
        if 0x0370 <= o <= 0x03FF or 0x1F00 <= o <= 0x1FFF:
            return "greek"
    if 0x10330 <= ord(text[0]) <= 0x1034A if text else False:
        return "gothic"
    if any(c in text for c in "ꜣꜥẖṯḏḳ"):
        return "egyptian"
    # الكلمةُ الأجنبيّةُ قد تُكتَبُ بحرفٍ عربيٍّ في المعاجمِ العربيّةِ المقارِنة
    if any("ء" <= c <= "ي" for c in text):
        return "arabic-script"
    return "akkadian"


