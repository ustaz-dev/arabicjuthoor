def oe_skeletons(word: str, script: str = "latin") -> list[tuple[list[str], str]]:
    """هياكلُ الكلمةِ الإنجليزيّةِ القديمةِ بأوسامِها، إضافةً لا بدلًا.

    وتُعرَضُ مع كلِّ هيكلٍ صورتُه بعدَ عدِّ المزدوجِ `sc` صوتًا واحدًا
    (شينُ الإنجليزيّةِ القديمة: `fisc` سمكة تُنطَقُ فِش)، فلا يُحسَبُ
    الصامتانِ المكتوبانِ صامتَينِ منطوقَين.
    """
    out: list[tuple[list[str], str]] = []
    seen: set[str] = set()

    def add(text: str, label: str) -> None:
        s = skeleton(text, script)
        key = "".join(s)
        if len(s) < 2 or key in seen:
            return
        seen.add(key)
        out.append((s, label))

    base = word.strip().lower()
    forms = [(base, "كما وردَت")]
    for end, why in OLD_ENGLISH_ENDINGS:
        if base.endswith(end) and len(base) - len(end) >= 3:
            forms.append((base[:-len(end)], f"بإسقاطِ {why}"))
            break
    for text, label in list(forms):
        if "sc" in text:
            # قراءتا المزدوج تُعرَضانِ معًا والمعنى يحكم: شينًا واحدةً
            # (fisc تُنطَقُ فش) أو صامتَينِ منفصلَينِ (ascian تُنطَقُ أسك)
            forms.append((text.replace("sc", "s"),
                          label + " والمزدوجُ sc صوتًا واحدًا"))
            # الفصلُ بصائتٍ يسقطُ في التهيكلِ فيبقى s وc حرفَينِ
            # بمروحتَيهما الكاملتَينِ (c تفتحُ على ج التي لا يملكُها k)
            forms.append((text.replace("sc", "sac"),
                          label + " والمزدوجُ sc صامتَينِ (s+c)"))
    for text, label in forms:
        add(text, label)
    return out


def _north_letters(word: str) -> str:
    w = unicodedata.normalize("NFC", str(word)).strip()
    w = w.translate(_DIAC_HEB).translate(FINALS)
    return re.sub(r"[^א-ת]", "", w)


def north_skeletons(word: str) -> list[tuple[list[str], str]]:
    """هياكلُ الكلمةِ الشماليّةِ كلُّها بأوسامِها، والأوّلُ هو «كما وردَت».

    وتُفتَحُ جبهتانِ لا واحدة: **علامةُ الحالِ والجمع**، و**الحرفُ العلّةُ** الذي
    تُسقِطُه القاعدةُ الحاليّةُ بلا استثناء. فالهاءُ في `אלהין` جذريّةٌ (إله) وقد
    أسقطَتها القاعدةُ، والياءُ في `ביתא` جذريّةٌ (بيت) وقد أسقطَتها.
    """
    base = _north_letters(word)
    if len(base) > 2 and base.endswith("א"):
        base = base[:-1]          # ألفُ التعريفِ الآراميّة، بقرارِ المؤلّف
    out: list[tuple[list[str], str]] = []
    seen: set[str] = set()

    def add(letters: str, label: str) -> None:
        if len(letters) < 2 or letters in seen:
            return
        seen.add(letters)
        out.append((list(letters), label))

    def drop_weak(s: str) -> str:
        return s[0] + "".join(c for c in s[1:] if c not in WEAK) if len(s) > 2 else s

    add(drop_weak(base), "كما وردَت")
    add(base, "بإبقاءِ حرفِ العلّةِ أصلًا")
    for end, why in NORTH_ENDINGS:
        if base.endswith(end) and len(base) - len(end) >= 2:
            stem = base[:-len(end)]
            add(drop_weak(stem), f"بإسقاطِ {why} ({end})")
            add(stem, f"بإسقاطِ {why} ({end}) وإبقاءِ حرفِ العلّة")
            break
    return out


def skeleton(word: str, script: str | None = None) -> list[str]:
    """الهيكلُ الصامتيُّ كقائمةِ حروفٍ يُبنى عليها التوليد."""
    w = unicodedata.normalize("NFC", str(word)).strip()
    script = script or detect(w)

    if script == "north":
        w = w.translate(_DIAC_HEB).translate(FINALS)
        w = re.sub(r"[^א-ת]", "", w)
        if len(w) > 2 and w.endswith("א"):
            w = w[:-1]
        if len(w) > 2:
            w = w[0] + "".join(c for c in w[1:] if c not in "והי")
        return list(w)

    if script == "coptic":
        w = w.lower()
        return [c for c in w if c in COPTIC_FAN and c not in COPTIC_VOWELS]

    if script == "greek":
        base = unicodedata.normalize("NFD", w.lower())
        base = "".join(c for c in base if not unicodedata.combining(c))
        return [c for c in base if c in GREEK_FAN and c not in GREEK_VOWELS]

    if script == "gothic":
        return [c for c in w if c in GOTHIC_FAN and c not in GOTHIC_VOWELS]

    if script == "persian":
        # الصوائتُ الطويلةُ تُطرَحُ من غيرِ الحرفِ الأوّل، كما يُفعَلُ بالشمالِ الساميّ
        w = re.sub(r"[ً-ْـ‌]", "", w)
        w = re.sub(r"[^ء-ی]", "", w)
        if len(w) > 2 and w.endswith("ه"):
            w = w[:-1]
        if len(w) > 2:
            w = w[0] + "".join(c for c in w[1:] if c not in PERSIAN_VOWELS)
        return [c for c in w if c in PERSIAN_FAN]

    if script in {"latin", "germanic"}:
        # الصوائتُ تُطرَحُ والمقارنةُ على الهيكلِ الصامتيّ، والحرفانِ المزدوجانِ
        # يُقرآنِ صوتًا واحدًا قبلَ أن يُقرأَ كلُّ حرفٍ وحدَه
        base = unicodedata.normalize("NFD", w.lower())
        base = "".join(c for c in base if not unicodedata.combining(c) or c in "̧")
        base = base.replace("̧", "")
        out, i = [], 0
        while i < len(base):
            two = base[i:i + 2].upper()
            if two in LATIN_DIGRAPH:
                out.append(two)
                i += 2
                continue
            c = base[i]
            if c in LATIN_VOWELS:
                i += 1
                continue
            if c in LATIN_FAN:
                out.append(c)
            i += 1
        # **الإدغامُ يُقاسُ على الأصلِ لا على الهيكل.** كان الحذفُ يجري بعدَ
        # طرحِ الصوائت، فيلتقي صامتانِ كانا مفصولَينِ بصائتٍ فيُدغَمانِ ظلمًا:
        # `Dadanu` (ددان) تُقرَأُ `دن`، و`Yatribu` سليمةٌ لأنّ صوامتَها مختلفة.
        # فلا يُحذَفُ إلّا ما كان مكرَّرًا **متلاصقًا في الكلمةِ نفسِها**.
        doubled = {base[i] for i in range(len(base) - 1) if base[i] == base[i + 1]}
        return [c for i, c in enumerate(out)
                if i == 0 or c != out[i - 1] or c not in doubled]

    if script == "arabic-script":
        w = re.sub(r"[^ء-ي]", "", w)
        core = [c for c in w if c not in ARABIC_WEAK] or list(w)
        return core[:4]

    if script == "egyptian":
        # **الحرفُ الكبيرُ يُصغَّرُ، وإلّا سقطَ صدرُ كلِّ عَلَم.** أُصلِحَ هذا في
        # الأكّاديّةِ واللاتينيّةِ ولم يُصلَحْ هنا، فكانَ اسمُ `Mina` موحِّدِ القطرَينِ
        # يُقرَأُ هيكلُه `i-n` بلا ميم. وكتابُ الآلهةِ 339 عَلَمًا من 600 صفّ،
        # أي أنّ أكثرَه كان يفقدُ صدرَ كلمتِه قبلَ أن يدخلَ المروحة.
        # **والعِبرةُ:** الإصلاحُ يُعَمَّمُ على الخطوطِ كلِّها ساعةَ يُكتَشَف، فمن
        # أصلحَ فرعًا وتركَ فرعَينِ عادَ العطبُ من حيثُ لا يُنتَظَر.
        w = w.lower()
        out, i = [], 0
        keys = sorted(EGYPTIAN_FAN, key=len, reverse=True)
        while i < len(w):
            for k in keys:
                if w[i:i + len(k)] == k:
                    out.append(k)
                    i += len(k)
                    break
            else:
                i += 1
        return out

    # الأكديّة: تُنزَعُ ميمةُ التنوينِ والصوائت
    #
    # **والحرفُ الكبيرُ يُصغَّرُ أوّلًا، وإلّا سقطَ أوّلُ حرفٍ من كلِّ عَلَم.** مفاتيحُ
    # المروحةِ صغيرةٌ كلُّها، والأعلامُ تُكتَبُ بحرفٍ كبير، فكانت `Padakku` تُقرَأُ
    # `دك` و`Ḫibrā` تُقرَأُ `بر` و`Yatribu` تُقرَأُ `ترب`. وقائمةُ نبونيد المسماريّةُ
    # كشفَتْه: خمسةٌ من ستّةِ مواضعَ فيها فقدَت صدرَها قبلَ أن تدخلَ المروحة.
    w = w.lower()
    w = AKKADIAN_MIMATION.sub("", w)
    out = []
    for c in w:
        if c in AKKADIAN_VOWELS:
            continue
        if c in AKKADIAN_FAN:
            out.append(c)
    # **الإدغامُ يُقاسُ على الأصلِ لا على الهيكل.** كان الحذفُ يجري بعدَ
    # طرحِ الصوائت، فيلتقي صامتانِ كانا مفصولَينِ بصائتٍ فيُدغَمانِ ظلمًا:
    # `Dadanu` (ددان) تُقرَأُ `دن`، و`Yatribu` سليمةٌ لأنّ صوامتَها مختلفة.
    # فلا يُحذَفُ إلّا ما كان مكرَّرًا **متلاصقًا في الكلمةِ نفسِها**.
    doubled = {w[i] for i in range(len(w) - 1) if w[i] == w[i + 1]}
    return [c for i, c in enumerate(out)
            if i == 0 or c != out[i - 1] or c not in doubled]


FANS = {
    "north": NORTH_FAN, "coptic": COPTIC_FAN, "greek": GREEK_FAN,
    "egyptian": EGYPTIAN_FAN, "akkadian": AKKADIAN_FAN,
    "arabic-script": ARABIC_SCRIPT_FAN,
    "latin": LATIN_FAN, "gothic": GOTHIC_FAN, "germanic": GERMANIC_FAN,
    "persian": PERSIAN_FAN,
}


def fan(word: str, script: str | None = None, limit: int = 400,
        geminate: bool = True) -> list[str]:
    """مروحةُ المرشَّحاتِ العربيّةِ للكلمة.

    **والمضاعَفُ يدخلُ فيها** (`geminate`): الفرعُ يكتبُ الصامتَ مرّةً والعربيّةُ
    تُضاعِفُه في بابٍ كاملٍ من أبوابِها، فـ`asher` بإزاءِ `شرر` و`tcher` بإزاءِ
    `ذرر` و`tchet` بإزاءِ `ذدد`. ومن قصرَ الهيكلَ ذا الصامتَينِ على مرشَّحٍ من
    حرفَينِ أغلقَ بابَ المضاعَفِ كلَّه وهو **أوضحُ صورةٍ للنواةِ الثنائيّةِ في
    العربيّةِ نفسِها**، فالمادّةُ الثنائيّةُ إذا صارت جذرًا ثلاثيًّا كرَّرَت آخرَها.
    """
    script = script or detect(word)
    sk = skeleton(word, script)
    # **اللاحقةُ الإعرابيّةُ تُطيلُ الهيكلَ فوقَ الحدِّ فتسقطُ الكلمةُ كلُّها.**
    # `argentum` هيكلُها r-g-n-t-m بخمسةِ صوامتَ فمروحتُها صفرٌ، وميمُها لاحقةٌ
    # لا حرفٌ من المادّة. وهي الفصيلةُ نفسُها التي رُئيَت في سينِ `rēx` وفي تاءِ
    # `עסקתא` وفي لاحقةِ `*-tḗr`. فإن جاوزَ الهيكلُ الحدَّ جُرِّبَ بإسقاطِ لاحقةٍ
    # واحدةٍ معروفةٍ في لسانِه، **ولا يُسقَطُ شيءٌ ما دامَ الهيكلُ صالحًا كما ورد**.
    skeletons = [sk]
    if script == "akkadian":
        # الرومنةُ الأكديّةُ قد تبدأُ بصائتٍ مكتوبٍ من غير علامة الوقف، مع أن
        # المقابلَ الساميَّ يثبت الهمزة: `Ayalu` بإزاء `أيل`. الصورةُ الجديدة
        # لا تمحو الهيكلَ القديم؛ تضيفُ إليه هيكلًا موسومًا بهمزة البدء فقط.
        # ونقيسُ البدء بعد NFD كي تدخل ā وأخواتُها في باب الصائت نفسه.
        source = unicodedata.normalize("NFD", str(word).strip().lower())
        if source[:1] in "aeiou" and 1 <= len(sk) <= 3:
            skeletons.append(["ʾ", *sk])
    if script in {"latin", "germanic", "greek"}:
        for end in LATIN_ENDINGS:
            if word.lower().endswith(end) and len(word) - len(end) >= 2:
                alt = skeleton(word[: -len(end)], script)
                if 2 <= len(alt) <= 4 and alt != sk:
                    skeletons.append(alt)
                break
    # المصريّةُ: تاءُ التأنيثِ وسينُ السببيّةِ وأخواتُهما بديلٌ موسومٌ لا بديلَ عنه
    if script == "egyptian":
        skeletons += [alt for alt, _ in egyptian_skeletons(sk)[1:]]

    # اللاتينيُّ والجرمانيُّ: ما جاوزَ هيكلُه الأربعةَ تُنزَعُ زوائدُ اشتقاقِه.
    # **ولا يُقتَطَعُ أوّلُ الراجعِ هنا**: الكلمةُ الطويلةُ لا يدخلُ هيكلُها
    # «كما وردَت» أصلًا لأنّه مجاوِزٌ للحدّ، فأوّلُ الراجعِ بديلٌ لا أصل.
    if script in {"latin", "germanic"} and len(sk) > 4:
        for alt, _ in latin_stem_skeletons(word, script):
            if alt not in skeletons:
                skeletons.append(alt)

    # الإنجليزيّةُ القديمةُ وأخواتُها الجرمانيّةُ بالخطِّ اللاتينيّ: نونُ المصدرِ
    # ونهاياتُ التصريفِ تُنزَعُ نصًّا والمزدوجُ sc يُعرَضُ صوتًا واحدًا، إضافةً
    # لا بدلًا في كلِّ حال (إصلاحُ مسبارِ 2026-08-17: انقلابُ 3 من 6).
    if script in {"latin", "germanic"}:
        for alt, _ in oe_skeletons(word, script):
            if alt not in skeletons:
                skeletons.append(alt)

    table = FANS[script]
    out: list[str] = []
    seen: set[str] = set()
    for s in skeletons:
        if not (2 <= len(s) <= 4):
            continue
        options = [table.get(c, ()) for c in s]
        if any(not o for o in options):
            continue
        for combo in itertools.islice(itertools.product(*options), limit):
            w = "".join(combo)
            if w not in seen:
                seen.add(w)
                out.append(w)
        if geminate and len(s) == 2:
            # **البابُ الأوسعُ الذي كان مغلقًا: المادّةُ المعتلّة.** الجذرُ العربيُّ
            # الأجوفُ والناقصُ والمثالُ فيه واوٌ أو ياءٌ **لا يقابلُها حرفٌ في
            # الكلمةِ الأجنبيّةِ لأنّها صائتٌ هناك**: صائتُ `remus` هو ياءُ `رمي`،
            # وصائتُ `turris` هو واوُ `طور`، وصائتُ `cuppa` هو واوُ `كوب`. فنحن
            # نطرحُ صوائتَ الفرعِ ثمّ نطلبُ جذرًا صامتيًّا خالصًا، **وثلثُ موادِّ
            # العربيّةِ معتلّ**. ومعها المضاعَفُ، وكلاهما وجهُ النواةِ الثنائيّةِ
            # حينَ تصيرُ جذرًا ثلاثيًّا: إمّا كرَّرَت آخرَها وإمّا استعانت بحرفِ علّة.
            for w in list(out):
                if len(w) != 2:
                    continue
                a, b = w[0], w[1]
                for cand in (w + w[-1],
                             a + "و" + b, a + "ي" + b, a + "ا" + b,
                             w + "و", w + "ي", w + "ا",
                             "و" + w, "ي" + w):
                    if cand not in seen and len(out) < limit * 3:
                        seen.add(cand)
                        out.append(cand)
    return out[: limit * 3]


